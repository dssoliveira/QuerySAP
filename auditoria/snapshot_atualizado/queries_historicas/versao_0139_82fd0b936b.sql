SELECT
    C."COLUMN_NAME",
    C."DATA_TYPE_NAME",
    C."LENGTH",
    C."SCALE"
FROM SYS.TABLE_COLUMNS C
WHERE
    C."TABLE_NAME" = 'OINV'
    AND (
        UPPER(C."COLUMN_NAME") LIKE '%NFE%'
        OR UPPER(C."COLUMN_NAME") LIKE '%NF%'
        OR UPPER(C."COLUMN_NAME") LIKE '%TOTAL%'
        OR UPPER(C."COLUMN_NAME") LIKE '%VAL%'
    )
ORDER BY
    C."COLUMN_NAME";
