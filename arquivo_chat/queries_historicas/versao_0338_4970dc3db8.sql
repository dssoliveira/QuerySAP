SELECT
    C."TABLE_NAME",
    C."COLUMN_NAME",
    C."DATA_TYPE_NAME",
    C."LENGTH"
FROM SYS.TABLE_COLUMNS C
WHERE
    C."SCHEMA_NAME" = CURRENT_SCHEMA
    AND (
        UPPER(C."COLUMN_NAME") LIKE '%LOG%'
        OR UPPER(C."COLUMN_NAME") LIKE '%DESCR%'
        OR UPPER(C."COLUMN_NAME") LIKE '%OBS%'
        OR UPPER(C."COLUMN_NAME") LIKE '%TEXT%'
        OR UPPER(C."COLUMN_NAME") LIKE '%MSG%'
    )
ORDER BY
    C."TABLE_NAME",
    C."POSITION";
