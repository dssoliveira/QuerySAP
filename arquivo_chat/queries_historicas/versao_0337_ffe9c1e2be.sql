SELECT
    C."TABLE_NAME",
    C."COLUMN_NAME",
    C."DATA_TYPE_NAME",
    C."LENGTH",
    C."SCALE"
FROM SYS.TABLE_COLUMNS C
WHERE
    C."SCHEMA_NAME" = CURRENT_SCHEMA
    AND (
        UPPER(C."TABLE_NAME") LIKE '%LOC1%'
        OR UPPER(C."TABLE_NAME") LIKE '%ICL%'
        OR UPPER(C."TABLE_NAME") LIKE '%LOG%'
    )
    AND (
        UPPER(C."COLUMN_NAME") LIKE '%CALL%'
        OR UPPER(C."COLUMN_NAME") LIKE '%OS%'
        OR UPPER(C."COLUMN_NAME") LIKE '%LOG%'
        OR UPPER(C."COLUMN_NAME") LIKE '%USER%'
        OR UPPER(C."COLUMN_NAME") LIKE '%USUARIO%'
        OR UPPER(C."COLUMN_NAME") LIKE '%USU%'
        OR UPPER(C."COLUMN_NAME") LIKE '%OPER%'
        OR UPPER(C."COLUMN_NAME") LIKE '%DATE%'
        OR UPPER(C."COLUMN_NAME") LIKE '%DATA%'
    )
ORDER BY
    C."TABLE_NAME",
    C."POSITION";
