SELECT
    C."TABLE_NAME",
    C."POSITION" AS "#",
    C."COLUMN_NAME",
    C."DATA_TYPE_NAME",
    C."LENGTH",
    C."SCALE"
FROM "SYS"."TABLE_COLUMNS" C
WHERE
    C."SCHEMA_NAME" = CURRENT_SCHEMA
    AND C."TABLE_NAME" IN ('OWTQ', 'WTQ1')
    AND (
        C."COLUMN_NAME" LIKE 'U_%'
        OR UPPER(C."COLUMN_NAME") LIKE '%CALL%'
        OR UPPER(C."COLUMN_NAME") LIKE '%OS%'
        OR UPPER(C."COLUMN_NAME") LIKE '%SERV%'
        OR UPPER(C."COLUMN_NAME") LIKE '%ORDEM%'
    )
ORDER BY
    C."TABLE_NAME",
    C."POSITION";
